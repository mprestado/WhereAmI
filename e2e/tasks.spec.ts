import { expect, test, type Page } from '@playwright/test'

async function openTaskView(page: Page, name: string) {
  await page.getByRole('button', { name: 'Workspace menu' }).click()
  const menu = page.getByRole('navigation', { name: 'Workspace options' })
  await menu.getByText('Tasks', { exact: true }).click()
  await menu.getByRole('button', { name, exact: true }).click()
}

test('captures undated tasks, edits and finds them across views and reload', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Create a goal' })).toBeVisible()
  await page.keyboard.press('Control+Shift+Space')
  const field = page.getByRole('textbox', { name: 'Quick capture task title' })
  await field.fill('Call the library')
  await field.press('Enter')
  await expect(field).toHaveValue('')
  await page.keyboard.press('Escape')
  await openTaskView(page, 'Inbox')
  await expect(page.getByRole('button', { name: 'Call the library' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Call the library' })).toBeVisible()
  await openTaskView(page, 'Today')
  await expect(page.getByRole('button', { name: 'Call the library' })).toHaveCount(0)
  await page.keyboard.press('Control+k')
  const search = page.getByRole('searchbox', { name: 'Search goals, objectives, and tasks' })
  await expect(search).toBeFocused()
  await search.fill('Call the lib')
  await search.press('Enter')
  const editor = page.getByRole('dialog', { name: 'Task details' })
  await expect(editor.getByRole('textbox', { name: 'Title' })).toHaveValue('Call the library')
  const tomorrow = await page.evaluate(() => {
    const date = new Date()
    date.setDate(date.getDate() + 1)
    return [date.getFullYear(), String(date.getMonth() + 1).padStart(2, '0'), String(date.getDate()).padStart(2, '0')].join('-')
  })
  await editor.getByLabel('Deadline').fill(tomorrow)
  await editor.getByLabel('Priority').selectOption('high')
  await editor.getByLabel('New checklist item').fill('Find card number')
  await editor.getByRole('button', { name: 'Save changes' }).click()
  await openTaskView(page, 'Upcoming')
  await expect(page.getByRole('button', { name: 'Call the library' })).toBeVisible()
  await page.getByRole('checkbox', { name: 'Complete Call the library' }).click()
  await expect(page.getByRole('checkbox', { name: 'Complete Call the library' })).toHaveCount(0)
  await openTaskView(page, 'Completed')
  await expect(page.getByRole('checkbox', { name: 'Complete Call the library' })).toBeChecked()
  await page.getByRole('checkbox', { name: 'Complete Call the library' }).click()
  await expect(page.getByRole('button', { name: 'Call the library' })).toHaveCount(0)
  await openTaskView(page, 'Inbox')
  await page.getByRole('button', { name: 'Call the library' }).click()
  await expect(editor.getByLabel('Checklist item 1', { exact: true })).toHaveValue('Find card number')
  await editor.getByRole('button', { name: 'Archive task' }).click()
  await editor.getByRole('button', { name: 'Save changes' }).click()
  await openTaskView(page, 'Archived')
  await page.getByRole('button', { name: 'Call the library' }).click()
  await editor.getByRole('button', { name: 'Delete task', exact: true }).click()
  await editor.getByRole('button', { name: 'Delete task', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Call the library' })).toHaveCount(0)
})

test('edits optional sub-objective work and reorders checklist rows in the task editor', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Create a goal' }).click()
  await page.getByRole('textbox', { name: 'Your goal' }).fill('Write the proposal')
  await page.getByRole('button', { name: 'Continue' }).click()
  await page.getByRole('textbox', { name: 'Objective 1', exact: true }).fill('Prepare the draft')
  await page.getByRole('button', { name: 'Add sub-objective' }).click()
  await page.getByRole('textbox', { name: 'Sub-objective 1 for objective 1' }).fill('Draft the outline')
  await page.getByRole('button', { name: 'Create goal' }).click()

  const present = page.getByRole('region', { name: 'Present', exact: true })
  await present.getByRole('button', { name: 'Actions for Draft the outline' }).click()
  await present.getByRole('button', { name: 'Task details' }).click()
  const editor = page.getByRole('dialog', { name: 'Task details' })
  await editor.getByRole('checkbox', { name: 'Optional in journey progress' }).check()
  await editor.getByLabel('New checklist item').fill('Read references')
  await editor.getByLabel('New checklist item').press('Enter')
  await editor.getByLabel('New checklist item').fill('Write the outline')
  await editor.getByLabel('New checklist item').press('Enter')
  await editor.getByRole('button', { name: 'Move checklist item 2 up' }).click()
  await expect(editor.getByRole('textbox', { name: 'Checklist item 1' })).toHaveValue('Write the outline')
  await editor.getByRole('checkbox', { name: 'Optional checklist item 1' }).check()
  await editor.getByRole('button', { name: 'Save changes' }).click()

  await expect(present.getByText('Optional', { exact: true })).toBeVisible()
  await expect(page.getByRole('progressbar', { name: 'Goal progress' })).toHaveAttribute('value', '0')
  await present.getByRole('button', { name: 'Mark objective complete' }).click()
  await expect(page.getByRole('progressbar', { name: 'Goal progress' })).toHaveAttribute('value', '100')
  await page.getByRole('region', { name: 'Past', exact: true }).getByText('Prepare the draft').click()
  await page.getByRole('button', { name: 'Actions for Draft the outline' }).click()
  await page.getByRole('button', { name: 'Task details' }).click()
  const reopened = page.getByRole('dialog', { name: 'Task details' })
  await expect(reopened.getByRole('checkbox', { name: 'Optional in journey progress' })).toBeChecked()
  await expect(reopened.getByRole('textbox', { name: 'Checklist item 1' })).toHaveValue('Write the outline')
  await expect(reopened.getByRole('checkbox', { name: 'Optional checklist item 1' })).toBeChecked()
})

test('mobile navigation, keyboard capture, theme persistence and export', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Create a goal' })).toBeVisible()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
  await page.keyboard.press('Control+Shift+Space')
  const dialog = page.getByRole('dialog', { name: 'Quick capture' })
  const field = dialog.getByRole('textbox', { name: 'Quick capture task title' })
  await expect(field).toBeFocused()
  await field.fill('Pack charger')
  await field.press('Enter')
  await expect(dialog.getByRole('status')).toHaveText('Added to Inbox.')
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await openTaskView(page, 'Inbox')
  await expect(page.getByRole('button', { name: 'Pack charger' })).toBeVisible()
  await page.getByRole('button', { name: 'Workspace menu' }).click()
  await page.getByRole('button', { name: 'Account and settings' }).click()
  await page.getByRole('button', { name: 'Dark', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.reload()
  await expect(page.getByRole('button', { name: 'Dark', exact: true })).toHaveAttribute('aria-pressed', 'true')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export workspace' }).click()
  expect((await download).suggestedFilename()).toMatch(/^whereami-workspace-.*\.json$/)
})

