import { expect, test } from '@playwright/test'

test('edits, reorders, and reopens work directly on the journey', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Create a goal' }).click()
  await page.getByRole('textbox', { name: 'Your goal' }).fill('Prepare a garden')
  await page.getByRole('button', { name: 'Continue' }).click()
  await page.getByRole('button', { name: 'Create goal' }).click()
  await expect(page.getByRole('progressbar', { name: 'Goal progress' })).toHaveAttribute('value', '0')

  const present = page.getByRole('region', { name: 'Present', exact: true })
  const future = page.getByRole('region', { name: 'Future', exact: true })
  const past = page.getByRole('region', { name: 'Past', exact: true })
  const addObjective = async (title: string) => {
    await present.getByRole('button', { name: 'Add objective', exact: true }).click()
    await present.getByRole('textbox', { name: 'New objective' }).fill(title)
    await present.getByRole('button', { name: 'Add', exact: true }).click()
  }

  await addObjective('Pick a planting area')
  await expect(present.getByRole('heading', { name: 'Pick a planting area' })).toBeVisible()
  await addObjective('Measure the space')
  await future.getByText('Measure the space', { exact: true }).click()
  await future.getByRole('button', { name: 'Actions for Measure the space' }).click()
  await future.getByRole('button', { name: 'Move earlier' }).click()
  await expect(present.getByRole('heading', { name: 'Measure the space' })).toBeVisible()

  await page.getByRole('button', { name: 'Prepare a garden', exact: true }).click()
  await page.getByRole('textbox', { name: 'goal title', exact: true }).fill('Prepare a balcony garden')
  await page.getByRole('textbox', { name: 'goal title', exact: true }).press('Enter')
  await expect(page.getByRole('heading', { name: 'Prepare a balcony garden', level: 1 })).toBeVisible()

  await present.getByRole('button', { name: 'Measure the space', exact: true }).click()
  await present.getByRole('textbox', { name: 'objective title', exact: true }).fill('Take balcony measurements')
  await present.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(present.getByRole('heading', { name: 'Take balcony measurements' })).toBeVisible()

  await present.getByRole('button', { name: 'Add sub-objective' }).click()
  await present.getByRole('textbox', { name: 'New sub-objective' }).fill('Measure railing')
  await present.getByRole('textbox', { name: 'New sub-objective' }).press('Enter')
  const checkbox = present.getByRole('checkbox', { name: 'Complete Measure railing' })
  await expect(checkbox).toBeVisible()
  await checkbox.focus()
  await checkbox.press('Space')
  const next = present.getByRole('heading', { name: 'Pick a planting area' })
  await expect(next).toBeVisible()
  await expect(next).toBeFocused()

  await past.getByText('Take balcony measurements', { exact: true }).click()
  await past.getByRole('checkbox', { name: 'Complete Measure railing' }).click()
  await expect(present.getByRole('heading', { name: 'Take balcony measurements' })).toBeVisible()
  await present.getByRole('button', { name: 'Actions for Measure railing' }).click()
  await present.getByRole('button', { name: 'Remove sub-objective' }).click()
  const confirmation = page.getByRole('dialog', { name: 'Remove sub-objective?' })
  await confirmation.getByRole('button', { name: 'Remove', exact: true }).click()
  await expect(confirmation).toBeHidden()
  await expect(present.getByRole('checkbox')).toHaveCount(0)
  await present.getByRole('button', { name: 'Mark objective complete' }).click()
  await expect(next).toBeVisible()
  await past.getByText('Take balcony measurements', { exact: true }).click()
  await past.getByRole('button', { name: 'Reopen objective' }).click()
  await expect(present.getByRole('heading', { name: 'Take balcony measurements' })).toBeVisible()
  await expect(page.getByRole('progressbar', { name: 'Goal progress' })).toHaveAttribute('value', '0')

  await page.reload()
  await expect(page.getByRole('heading', { name: 'Prepare a balcony garden', level: 1 })).toBeVisible()
  await expect(present.getByRole('heading', { name: 'Take balcony measurements' })).toBeVisible()
})

test('edits optional work and order in a task list without advancing the view', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 800 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Create a goal' }).click()
  await page.getByRole('textbox', { name: 'Your goal' }).fill('Weekend jobs')
  await page.getByRole('radio', { name: 'Task list', exact: true }).check()
  await page.getByRole('button', { name: 'Continue' }).click()
  await page.getByRole('textbox', { name: 'Objective 1', exact: true }).fill('Clean the kitchen')
  await page.getByRole('button', { name: 'Add objective', exact: true }).click()
  await page.getByRole('textbox', { name: 'Objective 2', exact: true }).fill('Tidy the patio')
  await page.getByRole('button', { name: 'Create goal', exact: true }).click()

  const list = page.getByRole('region', { name: 'Task list' })
  const progress = page.getByRole('progressbar', { name: 'Goal progress' })
  await expect(list.getByRole('heading')).toHaveText(['Clean the kitchen', 'Tidy the patio'])
  await expect(page.getByRole('region', { name: 'Present', exact: true })).toHaveCount(0)
  const kitchen = list.locator('.journey-objective').filter({ has: page.getByRole('heading', { name: 'Clean the kitchen' }) })
  const patio = list.locator('.journey-objective').filter({ has: page.getByRole('heading', { name: 'Tidy the patio' }) })
  async function addToKitchen(title: string, optional: boolean) {
    await kitchen.getByRole('button', { name: 'Add sub-objective' }).click()
    await kitchen.getByRole('textbox', { name: 'New sub-objective' }).fill(title)
    if (optional) await kitchen.getByRole('checkbox', { name: 'Optional', exact: true }).check()
    await kitchen.getByRole('button', { name: 'Add', exact: true }).click()
  }
  await addToKitchen('Wash the dishes', false)
  await addToKitchen('Polish the taps', true)

  await kitchen.getByRole('button', { name: 'Actions for Polish the taps' }).click()
  await kitchen.getByRole('button', { name: 'Move earlier' }).click()
  await expect(kitchen.getByRole('checkbox').first()).toHaveAccessibleName('Complete Polish the taps')
  await kitchen.getByRole('checkbox', { name: 'Complete Wash the dishes' }).click()
  await expect(progress).toHaveAttribute('value', '50')
  await expect(kitchen.getByRole('checkbox', { name: 'Complete Polish the taps' })).not.toBeChecked()

  await kitchen.getByRole('button', { name: 'Actions for Polish the taps' }).click()
  await kitchen.getByRole('button', { name: 'Move to objective' }).click()
  await kitchen.getByRole('combobox', { name: 'Objective', exact: true }).selectOption({ label: 'Tidy the patio' })
  await kitchen.getByRole('button', { name: 'Move', exact: true }).click()
  await expect(patio.getByRole('checkbox', { name: 'Complete Polish the taps' })).toBeVisible()
  await patio.getByRole('button', { name: 'Actions for Tidy the patio' }).click()
  await patio.getByRole('button', { name: 'Make optional', exact: true }).click()
  await expect(progress).toHaveAttribute('value', '100')
  await expect(patio.getByText('Optional', { exact: true })).toHaveCount(2)

  await page.reload()
  await expect(list.getByRole('heading')).toHaveText(['Clean the kitchen', 'Tidy the patio'])
  await expect(progress).toHaveAttribute('value', '100')
  await expect(patio.getByRole('checkbox', { name: 'Complete Polish the taps' })).not.toBeChecked()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(360)
})
