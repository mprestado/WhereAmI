import { expect, test } from '@playwright/test'

test('starts with a quiet canvas and advances through the saved journey on desktop and mobile', async ({ page }) => {
  await page.setViewportSize({ width: 1360, height: 900 })
  await page.goto('/')
  const start = page.getByRole('button', { name: 'Create a goal' })
  await expect(start).toBeVisible()
  await expect(page.getByRole('navigation')).toHaveCount(0)
  await expect(page.getByRole('main').getByRole('button')).toHaveCount(1)
  await start.click()
  await expect(page.getByRole('heading', { name: 'What is your goal?' })).toBeVisible()
  await page.getByRole('textbox', { name: 'Your goal' }).fill('Finish the research project')
  await page.getByRole('button', { name: 'Continue' }).click()

  await page.getByRole('textbox', { name: 'Objective 1', exact: true }).fill('Revise methodology')
  await page.getByRole('button', { name: 'Add sub-objective', exact: true }).click()
  await page.getByRole('textbox', { name: 'Sub-objective 1 for objective 1' }).fill('Review the framework')
  await page.getByRole('button', { name: 'Add sub-objective', exact: true }).click()
  await page.getByRole('textbox', { name: 'Sub-objective 2 for objective 1' }).fill('Record the changes')
  await page.getByRole('button', { name: 'Add objective', exact: true }).click()
  await page.getByRole('textbox', { name: 'Objective 2', exact: true }).fill('Build the prototype')
  await page.getByRole('button', { name: 'Add sub-objective', exact: true }).last().click()
  await page.getByRole('textbox', { name: 'Sub-objective 1 for objective 2' }).fill('Prepare the dataset')
  await page.getByRole('button', { name: 'Create goal', exact: true }).click()

  const past = page.getByRole('region', { name: 'Past', exact: true })
  const present = page.getByRole('region', { name: 'Present', exact: true })
  const future = page.getByRole('region', { name: 'Future', exact: true })
  const progress = page.getByRole('progressbar', { name: 'Goal progress' })
  await expect(present.getByRole('heading', { name: 'Revise methodology' })).toBeVisible()
  await expect(future.getByText('Build the prototype', { exact: true })).toBeVisible()
  await expect(future.getByRole('checkbox', { name: 'Complete Prepare the dataset' })).toHaveCount(0)
  expect((await past.boundingBox())!.x).toBeLessThan((await present.boundingBox())!.x)
  expect((await present.boundingBox())!.x).toBeLessThan((await future.boundingBox())!.x)
  await expect(progress).toHaveAttribute('value', '0')
  await present.getByRole('checkbox', { name: 'Complete Review the framework' }).click()
  await expect(progress).toHaveAttribute('value', '33')
  await present.getByRole('checkbox', { name: 'Complete Record the changes' }).click()
  await expect(past.getByText('Revise methodology', { exact: true })).toBeVisible()
  await expect(present.getByRole('heading', { name: 'Build the prototype' })).toBeVisible()
  await expect(progress).toHaveAttribute('value', '66')

  await page.setViewportSize({ width: 360, height: 800 })
  await expect(page.getByRole('button', { name: /^Past/ })).toBeVisible()
  await expect(past.getByText('Revise methodology', { exact: true })).toBeHidden()
  expect((await present.boundingBox())!.y).toBeLessThan((await past.boundingBox())!.y)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(360)
  await page.getByRole('button', { name: /^Past/ }).click()
  await expect(past.getByText('Revise methodology', { exact: true })).toBeVisible()
  await page.reload()
  await expect(present.getByRole('heading', { name: 'Build the prototype' })).toBeVisible()
  await expect(progress).toHaveAttribute('value', '66')
})

test('switches goals through the corner menu and remembers the selection on a bare launch URL', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Create a goal' }).click()
  for (const name of ['Study the field notes', 'Build the prototype']) {
    await page.getByRole('textbox', { name: 'Your goal' }).fill(name)
    await page.getByRole('button', { name: 'Continue' }).click()
    await page.getByRole('button', { name: 'Create goal', exact: true }).click()
    await expect(page.getByRole('heading', { name })).toBeVisible()
    if (name === 'Study the field notes') {
      await page.getByRole('button', { name: 'Workspace menu' }).click()
      await page.getByRole('button', { name: 'Add goal or task list' }).click()
    }
  }
  await page.getByRole('button', { name: 'Workspace menu' }).click()
  await page.getByText('Switch goal or list', { exact: true }).click()
  await page.getByRole('button', { name: 'Study the field notes', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Study the field notes' })).toBeVisible()
  await expect(page.getByRole('navigation')).toHaveCount(0)
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Study the field notes' })).toBeVisible()
})
